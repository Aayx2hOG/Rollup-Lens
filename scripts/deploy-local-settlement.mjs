import { existsSync, readFileSync } from "node:fs";
import { chmod, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const envFile = resolve(root, ".env.operator.local");
loadLocalEnv(resolve(root, "local_testing/state.env"));

const apiUrl = (process.env.SETTLEMENT_API_URL ?? "http://127.0.0.1:3000").replace(/\/$/, "");
const rpcUrl = process.env.EVM_RPC_URL ?? "http://127.0.0.1:8545";
const privateKey = process.env.EVM_PRIVATE_KEY;
const databaseUrl = process.env.DATABASE_URL;
const directDatabaseUrl = process.env.DIRECT_DATABASE_URL ?? databaseUrl;
const l1DepositInbox = process.env.L1_DEPOSIT_INBOX;
const l1DepositDeploymentBlock = process.env.L1_DEPOSIT_DEPLOYMENT_BLOCK ?? "0";

if (!privateKey || !databaseUrl || !l1DepositInbox) {
  fail("Set EVM_PRIVATE_KEY, DATABASE_URL, and L1_DEPOSIT_INBOX before running this command.");
}
if (!/^\d+$/.test(l1DepositDeploymentBlock)) {
  fail("L1_DEPOSIT_DEPLOYMENT_BLOCK must be a non-negative integer.");
}

await requireJsonRpc();
await requireContractCode(l1DepositInbox, "L1_DEPOSIT_INBOX");
const summary = await fetchJson(`${apiUrl}/chain/summary`, "explorer API");
if (!summary.genesis_finalized || !summary.state_root) {
  fail("Genesis is not initialized. Run `cargo run -p explorer-api -- --initialize-genesis genesis.json` first.");
}

console.log("Building the prover, settlement client, and operator...");
await run("cargo", ["build", "--release", "-p", "validity-prover", "-p", "settlement-client", "-p", "operator"]);

const programVkey = (await run("./target/release/validity-prover", ["vkey"], true)).trim();
const genesisRoot = withHexPrefix(summary.state_root);
const sequencer = (await run("cast", ["wallet", "address", privateKey], true)).trim();

console.log("Deploying the matching SP1 Groth16 verifier...");
const verifier = await deploy(
  "lib/sp1-contracts/contracts/src/v6.1.0/SP1VerifierGroth16.sol:SP1Verifier",
  [],
);

console.log("Deploying ValidityRollupSettlement...");
const settlement = await deploy(
  "contracts/ValidityRollupSettlement.sol:ValidityRollupSettlement",
  [genesisRoot, verifier.address, programVkey, l1DepositInbox],
);

console.log(`Configuring ${sequencer} as the settlement sequencer...`);
await run("cast", [
  "send",
  settlement.address,
  "setSequencer(address)",
  sequencer,
  "--rpc-url",
  rpcUrl,
  "--private-key",
  privateKey,
]);

const chainId = Number.parseInt(await jsonRpc("eth_chainId", []), 16);
const env = [
  "# Generated by `bun run settlement:deploy:local`; contains secrets. Do not commit.",
  `DATABASE_URL=${quote(databaseUrl)}`,
  `DIRECT_DATABASE_URL=${quote(directDatabaseUrl)}`,
  `SETTLEMENT_API_URL=${quote(apiUrl)}`,
  `EVM_RPC_URL=${quote(rpcUrl)}`,
  `ROLLUP_SETTLEMENT_CONTRACT=${quote(settlement.address)}`,
  `L1_DEPOSIT_INBOX=${quote(l1DepositInbox)}`,
  `EVM_PRIVATE_KEY=${quote(privateKey)}`,
  `EVM_DEPLOYMENT_BLOCK=${settlement.blockNumber}`,
  "EVM_CONFIRMATIONS=0",
  `L1_DEPOSIT_DEPLOYMENT_BLOCK=${l1DepositDeploymentBlock}`,
  "L1_DEPOSIT_REORG_LOOKBACK=12",
  `VITE_L1_DEPOSIT_INBOX=${quote(l1DepositInbox)}`,
  `VITE_ROLLUP_SETTLEMENT_CONTRACT=${quote(settlement.address)}`,
  `VALIDITY_PROVER_BIN=${quote(resolve(root, "target/release/validity-prover"))}`,
  `SETTLEMENT_CLIENT_BIN=${quote(resolve(root, "target/release/settlement-client"))}`,
  "",
].join("\n");
await writeFile(envFile, env, { mode: 0o600 });
await chmod(envFile, 0o600);

console.log(`\nLocal settlement deployment complete (chain ${chainId}).`);
console.log(`Verifier:   ${verifier.address}`);
console.log(`Settlement: ${settlement.address}`);
console.log(`Config:     ${envFile}`);
console.log("Start automation with: set -a; source .env.operator.local; set +a; cargo run -p operator");

async function deploy(contract, constructorArgs) {
  const output = await run("forge", [
    "create",
    contract,
    "--broadcast",
    "--json",
    "--rpc-url",
    rpcUrl,
    "--private-key",
    privateKey,
    ...(constructorArgs.length ? ["--constructor-args", ...constructorArgs] : []),
  ], true);
  let result;
  try {
    result = JSON.parse(output);
  } catch {
    fail(`Could not parse forge deployment output:\n${output}`);
  }
  const address = result.deployedTo ?? result.deployed_to;
  const transactionHash = result.transactionHash ?? result.transaction_hash;
  if (!address || !transactionHash) fail(`Forge did not return a deployment address and transaction hash:\n${output}`);
  const receipt = await waitForReceipt(transactionHash);
  return { address, blockNumber: Number.parseInt(receipt.blockNumber, 16) };
}

async function waitForReceipt(transactionHash) {
  for (let attempt = 0; attempt < 30; attempt++) {
    const receipt = await jsonRpc("eth_getTransactionReceipt", [transactionHash]);
    if (receipt) {
      if (receipt.status !== "0x1") fail(`Deployment transaction reverted: ${transactionHash}`);
      return receipt;
    }
    await Bun.sleep(250);
  }
  fail(`Timed out waiting for deployment transaction: ${transactionHash}`);
}

async function requireJsonRpc() {
  try {
    await jsonRpc("eth_chainId", []);
  } catch (error) {
    fail(`Cannot reach EVM RPC at ${rpcUrl}: ${error.message}`);
  }
}

async function requireContractCode(address, name) {
  const code = await jsonRpc("eth_getCode", [address, "latest"]);
  if (!code || code === "0x") {
    fail(`${name}=${address} has no code on ${rpcUrl}. Start Anvil with the persisted state file or deploy L1DepositInbox and update local_testing/state.env.`);
  }
}

async function jsonRpc(method, params) {
  const response = await fetch(rpcUrl, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }),
  });
  const body = await response.json();
  if (!response.ok || body.error) throw new Error(body.error?.message ?? `HTTP ${response.status}`);
  return body.result;
}

async function fetchJson(url, service) {
  try {
    const response = await fetch(url);
    if (!response.ok) fail(`${service} returned HTTP ${response.status} from ${url}`);
    return await response.json();
  } catch (error) {
    fail(`Cannot reach ${service} at ${url}: ${error.message}`);
  }
}

async function run(command, args, capture = false) {
  const process = Bun.spawn([command, ...args], {
    cwd: root,
    env: processEnv(),
    stdout: capture ? "pipe" : "inherit",
    stderr: capture ? "pipe" : "inherit",
  });
  const [exitCode, stdout, stderr] = await Promise.all([
    process.exited,
    capture ? new Response(process.stdout).text() : "",
    capture ? new Response(process.stderr).text() : "",
  ]);
  if (exitCode !== 0) fail(`${command} failed with exit code ${exitCode}${stderr ? `:\n${stderr}` : ""}`);
  return stdout;
}

function processEnv() {
  return { ...process.env, CARGO_TERM_COLOR: "always" };
}

function loadLocalEnv(filePath) {
  if (!existsSync(filePath)) return;
  const content = readFileSync(filePath, "utf8");
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const separator = trimmed.indexOf("=");
    if (separator === -1) continue;
    const key = trimmed.slice(0, separator).trim();
    if (!/^[A-Z0-9_]+$/.test(key) || process.env[key]) continue;
    process.env[key] = unquoteEnvValue(trimmed.slice(separator + 1).trim());
  }
}

function unquoteEnvValue(value) {
  if (
    (value.startsWith("'") && value.endsWith("'"))
    || (value.startsWith('"') && value.endsWith('"'))
  ) {
    return value.slice(1, -1);
  }
  return value;
}

function withHexPrefix(value) {
  return value.startsWith("0x") ? value : `0x${value}`;
}

function quote(value) {
  return JSON.stringify(value);
}

function fail(message) {
  console.error(`error: ${message}`);
  process.exit(1);
}
